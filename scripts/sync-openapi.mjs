#!/usr/bin/env node
/**
 * Pulls Campfire's live OpenAPI spec and webhooks guide and regenerates:
 *   - test/fixtures/campfire-paths.json: every path, method and accepted
 *     query/body parameter, which the description tests check the node against
 *   - nodes/CampfireTrigger/events.ts: the webhook topics the trigger offers,
 *     read from the topics table in Campfire's webhooks guide (the spec does
 *     not list them)
 *
 * Run with `npm run sync:openapi` after Campfire ships API changes.
 */
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC_URL = 'https://api.meetcampfire.com/api/schema?format=json';
const WEBHOOKS_GUIDE_URL = 'https://docs.campfire.ai/guides/webhooks.md';
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

function resolver(spec) {
	return (node) => {
		let current = node;
		while (current && typeof current === 'object' && '$ref' in current) {
			current = current.$ref
				.split('/')
				.slice(1)
				.reduce((value, key) => value[key], spec);
		}
		return current;
	};
}

/** Top-level property names of a schema, across allOf/anyOf/oneOf branches. */
function propertyNames(schema, resolve, seen = new Set()) {
	const resolved = resolve(schema);
	if (!resolved || typeof resolved !== 'object' || seen.has(resolved)) return [];
	seen.add(resolved);
	const names = Object.keys(resolved.properties ?? {});
	for (const key of ['allOf', 'anyOf', 'oneOf']) {
		for (const branch of resolved[key] ?? []) names.push(...propertyNames(branch, resolve, seen));
	}
	return names;
}

/**
 * Some query parameters are only named in an operation's description, in a
 * "**Query Parameters:**" list such as "- `model` (required): ...".
 */
function describedQueryParameters(description = '') {
	const section = description.split('**Query Parameters:**')[1];
	if (!section) return [];
	const block = section.split('**')[0];
	return [...block.matchAll(/^\s*-\s*`([a-z_]+)`/gm)].map((match) => match[1]);
}

function describeEndpoints(spec) {
	const resolve = resolver(spec);
	const endpoints = {};
	for (const [path, operations] of Object.entries(spec.paths)) {
		for (const method of METHODS) {
			const operation = operations[method];
			if (!operation) continue;
			const query = (operation.parameters ?? [])
				.map(resolve)
				.filter((parameter) => parameter.in === 'query')
				.map((parameter) => parameter.name);
			query.push(...describedQueryParameters(operation.description));
			const content = resolve(operation.requestBody)?.content ?? {};
			const schema = content['application/json']?.schema ?? content['multipart/form-data']?.schema;
			const body = schema ? propertyNames(schema, resolve) : [];
			endpoints[path] ??= {};
			endpoints[path][method.toUpperCase()] = {
				query: [...new Set(query)].sort(),
				body: [...new Set(body)].sort(),
			};
		}
	}
	return endpoints;
}

/** Reads "| Invoices | `Invoice.created`, `Invoice.updated` |" rows from the topics table. */
function webhookTopics(guide) {
	const section = guide.split('## Topics')[1]?.split('\n## ')[0] ?? '';
	const topics = [...section.matchAll(/`([A-Za-z]+\.[a-z]+)`/g)].map((match) => match[1]);
	if (topics.length === 0) throw new Error('No webhook topics found in the webhooks guide');
	return [...new Set(topics)];
}

function topicName(topic) {
	const [object, action] = topic.split('.');
	const words = object.replace(/([a-z])([A-Z])/g, '$1 $2');
	return `${words} ${action.charAt(0).toUpperCase()}${action.slice(1)}`;
}

async function fetchOk(url) {
	const response = await fetch(url);
	if (!response.ok) throw new Error(`${url} answered ${response.status}`);
	return response;
}

const spec = await (await fetchOk(SPEC_URL)).json();
const guide = await (await fetchOk(WEBHOOKS_GUIDE_URL)).text();

const endpoints = describeEndpoints(spec);
await writeFile(
	join(ROOT, 'test/fixtures/campfire-paths.json'),
	`${JSON.stringify(endpoints, null, '\t')}\n`,
);

const topics = webhookTopics(guide)
	.map((value) => ({ name: topicName(value), value }))
	.sort((a, b) => a.name.localeCompare(b.name));
await writeFile(
	join(ROOT, 'nodes/CampfireTrigger/events.ts'),
	`// Generated by scripts/sync-openapi.mjs from Campfire's webhooks guide. Do not edit by hand.
import type { INodePropertyOptions } from 'n8n-workflow';

export const WEBHOOK_TOPICS: INodePropertyOptions[] = [
${topics.map(({ name, value }) => `\t{ name: '${name}', value: '${value}' },`).join('\n')}
];
`,
);

console.log(`${Object.keys(endpoints).length} paths, ${topics.length} webhook topics`);
